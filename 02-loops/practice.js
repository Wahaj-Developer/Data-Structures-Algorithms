// --- what is a loop? ---
// a loop repeats a task multiple times without writing the same code again and again

// without a loop
console.log("Hello");
console.log("Hello");
console.log("Hello");
console.log("Hello");
console.log("Hello");

// with a loop
// for (start, end, change)
for (let i = 1; i <= 5; i++) {
  console.log("Hello");
}
// Output: Hello (5 times)